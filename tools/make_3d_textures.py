"""Bundle local WebP art as data URLs for Three.js under file://.

Development-time only. WebGL cannot sample file-origin images via TextureLoader
in restrictive browsers; data URLs avoid that without a server or runtime build.
"""

import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIECES = ("pawn", "knight", "bishop", "rook", "queen", "king")
REALMS = ("highlands", "volcano", "glacier", "citadels", "desert")


def main():
    paths = [Path("assets/pieces") / army / f"{piece}.webp"
             for army in ("dawn", "shadow") for piece in PIECES]
    paths += [Path("assets/materials") / f"{realm}.webp" for realm in REALMS]
    urls = {path.as_posix(): "data:image/webp;base64," + base64.b64encode((ROOT / path).read_bytes()).decode("ascii")
            for path in paths}
    output = ROOT / "assets/3d-textures.js"
    output.write_text("/* Generated by tools/make_3d_textures.py; all images stay local. */\n"
                      "window.FantasyChess = window.FantasyChess || {};\n"
                      "window.FantasyChess.TextureData = Object.freeze(" + json.dumps(urls, separators=(",", ":")) + ");\n",
                      encoding="utf-8")
    print(f"Bundled {len(urls)} textures into {output.name} ({output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
